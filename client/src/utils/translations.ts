export function getLocalizedCategoryName(name: string, lang: Language): string {
  if (lang === 'ru' && CATEGORY_NAME_RU[name]) {
    return CATEGORY_NAME_RU[name];
  }
  return name;
}

export function formatCategoryCount(count: number, lang: Language): string {
  if (lang !== 'ru') return `${count} ${count === 1 ? 'category' : 'categories'}`;

  const mod10 = count % 10;
  const mod100 = count % 100;
  let word = 'категорий';
  if (mod10 === 1 && mod100 !== 11) word = 'категория';
  else if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) word = 'категории';
  return `${count} ${word}`;
}

export function formatTransactionCount(count: number, lang: Language): string {
  if (lang !== 'ru') return `${count} ${count === 1 ? 'transaction' : 'transactions'}`;
  const form = new Intl.PluralRules('ru').select(count);
  return `${count} ${form === 'one' ? 'операция' : form === 'few' ? 'операции' : 'операций'}`;
}
